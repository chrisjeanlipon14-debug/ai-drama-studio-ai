/* ----------------------------------
   SAFE HTML
---------------------------------- */

function escapeHtml(value) {
  return String(value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

/* ----------------------------------
   CHAT DISPLAY
---------------------------------- */

function addMessageToChat(role, content) {
  const message = document.createElement("div");
  message.className =
    "message " +
    (role === "user" ? "user-message" : "assistant-message");

  const paragraph = document.createElement("p");
  paragraph.textContent = content;

  message.appendChild(paragraph);
  chatMessages.appendChild(message);

  chatMessages.scrollTop = chatMessages.scrollHeight;

  return message;
}

/* ----------------------------------
   FIND SECTION
---------------------------------- */

function findSection(text, names) {
  const lines = text.split("\n");

  let start = -1;

  for (let i = 0; i < lines.length; i++) {
    const clean = lines[i]
      .replace(/\*/g, "")
      .replace(/#/g, "")
      .trim()
      .toLowerCase();

    if (names.some((name) => clean.includes(name))) {
      start = i + 1;
      break;
    }
  }

  if (start === -1) return "";

  const result = [];

  for (let i = start; i < lines.length; i++) {
    const clean = lines[i]
      .replace(/\*/g, "")
      .replace(/#/g, "")
      .trim()
      .toLowerCase();

    const isNextSection =
      clean.includes("originality check") ||
      clean.includes("continuity check") ||
      clean.includes("production notes") ||
      clean.includes("character") ||
      clean.includes("scene-by-scene") ||
      clean.includes("scene breakdown") ||
      clean === "characters" ||
      clean === "scenes";

    if (isNextSection && result.length > 0) break;

    result.push(lines[i]);
  }

  return result.join("\n").trim();
}

/* ----------------------------------
   EXTRACT TITLE
---------------------------------- */

function extractTitle(text) {
  const patterns = [
    /title\s*[:\-]\s*(.+)/i,
    /story title\s*[:\-]\s*(.+)/i,
    /###\s*(.+)/
  ];

  for (const pattern of patterns) {
    const match = text.match(pattern);

    if (match && match[1]) {
      return match[1]
        .replace(/\*\*/g, "")
        .replace(/^["']|["']$/g, "")
        .trim();
    }
  }

  return "AI-Generated Drama";
}

/* ----------------------------------
   EXTRACT GENRE
---------------------------------- */

function extractGenre(text) {
  const match = text.match(/genre\s*[:\-]\s*(.+)/i);

  if (match && match[1]) {
    return match[1]
      .replace(/\*\*/g, "")
      .trim();
  }

  return "Drama";
}

/* ----------------------------------
   EXTRACT CHARACTERS
---------------------------------- */

function renderCharacters(text) {
  const section = findSection(text, [
    "main characters",
    "characters",
    "character dna"
  ]);

  if (!section) {
    return `
      <div class="character">
        <div class="character-name">Characters</div>
        <div class="character-role">See complete AI plan below.</div>
        <div class="character-dna">
          Character information was generated by the AI Drama Engine.
        </div>
      </div>
    `;
  }

  const lines = section
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);

  const blocks = [];
  let current = [];

  for (const line of lines) {
    if (
      /^(\d+[\.\)]|[-•])\s*/.test(line) &&
      current.length > 0
    ) {
      blocks.push(current.join(" "));
      current = [];
    }

    current.push(line);
  }

  if (current.length) blocks.push(current.join(" "));

  return blocks
    .slice(0, 8)
    .map((block) => {
      const cleaned = block
        .replace(/^(\d+[\.\)]|[-•])\s*/, "")
        .replace(/\*\*/g, "")
        .trim();

      return `
        <div class="character">
          <div class="character-name">${escapeHtml(cleaned)}</div>
          <div class="character-role">AI Drama Character</div>
          <div class="character-dna">
            Character DNA generated and locked for continuity.
          </div>
        </div>
      `;
    })
    .join("");
}

/* ----------------------------------
   EXTRACT SCENES
---------------------------------- */

function renderScenes(text) {
  const section = findSection(text, [
    "scene-by-scene plan",
    "scene breakdown",
    "scenes"
  ]);

  if (!section) {
    return `
      <div class="scene">
        <div class="scene-number">SCENES</div>
        <div class="scene-title">Production scenes generated</div>
        <div class="scene-description">
          See the complete AI production plan below.
        </div>
      </div>
    `;
  }

  const lines = section
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);

  let sceneNumber = 0;
  const scenes = [];
  let current = [];

  function saveScene() {
    if (current.length > 0) {
      sceneNumber++;

      const combined = current
        .join(" ")
        .replace(/\*\*/g, "")
        .trim();

      scenes.push(`
        <div class="scene">
          <div class="scene-number">
            SCENE ${String(sceneNumber).padStart(2, "0")}
          </div>
          <div class="scene-title">
            ${escapeHtml(combined.substring(0, 90))}
          </div>
          <div class="scene-description">
            ${escapeHtml(combined)}
          </div>
        </div>
      `);

      current = [];
    }
  }

  for (const line of lines) {
    const isScene =
      /^scene\s*\d+/i.test(line) ||
      /^\d+[\.\)]\s/.test(line) ||
      /^\*\*scene/i.test(line);

    if (isScene) {
      saveScene();
    }

    current.push(line);
  }

  saveScene();

  return scenes.slice(0, 30).join("");
}

